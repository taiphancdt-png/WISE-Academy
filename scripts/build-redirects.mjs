// Writes public/_redirects from src/data/legacy-redirects.json (runs before every build).
// Netlify applies these at the edge in one hop, with or without the old WordPress trailing slash;
// next.config.ts keeps the same list as a fallback for local runs.
import { readFileSync, writeFileSync } from "node:fs";

const rules = JSON.parse(readFileSync(new URL("../src/data/legacy-redirects.json", import.meta.url), "utf8"));
const lines = rules.map(({ source, destination }) => `${source.replace(/:path\*$/, "*")}  ${destination}  301`);
writeFileSync(
  new URL("../public/_redirects", import.meta.url),
  ["# Generated by scripts/build-redirects.mjs from src/data/legacy-redirects.json. Do not edit.", ...lines, ""].join("\n"),
);
